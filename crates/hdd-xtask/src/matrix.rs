//! Capability matrix tooling (T-0010, R-07): `matrix generate` and `matrix check`.
//!
//! Rows are derived from the task blocks (one `REQ-<PREFIX>-<k>` per task, section 0.9). Status comes from the task table of
//! `STATUS.md`; tests and evidence come from `docs/matrix-links.toml`. A row can only advance as far as its links allow:
//!
//! * `red`, `green`, `verified`, `accepted`, `done` need at least one test (`path::name`, which must exist) or an explicit `deferred` reason;
//! * `verified`, `accepted`, `done` need evidence (`path@sha256`, hash verified);
//! * `accepted` and `done` need a passing run record: evidence pointing at a verify summary (`*.json` with `steps`) without a FAIL.

use std::collections::BTreeMap;
use std::path::Path;

use serde::Deserialize;

use crate::spec;
use crate::tasks::{self, Model};
use crate::util::{Finding, Result, md_cell, read_bytes, read_text, rel, sha256_hex, write_text};

/// Links of one task.
#[derive(Debug, Deserialize, Clone, Default)]
pub struct Links {
    /// Task id.
    pub id: String,
    /// Test references `path::fn_name` (or `path` alone for a script/suite file).
    #[serde(default)]
    pub tests: Vec<String>,
    /// Evidence references `path@sha256`.
    #[serde(default)]
    pub evidence: Vec<String>,
    /// Reason when the requirement is explicitly deferred.
    #[serde(default)]
    pub deferred: String,
}

/// Parsed `docs/matrix-links.toml`.
#[derive(Debug, Deserialize, Default, Clone)]
pub struct LinksFile {
    /// Per-task links.
    #[serde(default)]
    pub task: Vec<Links>,
}

/// Load the links file (missing file means no links).
pub fn load_links(root: &Path) -> Result<LinksFile> {
    let p = root.join("docs").join("matrix-links.toml");
    if !p.is_file() {
        return Ok(LinksFile::default());
    }
    Ok(toml::from_str(&read_text(&p)?)?)
}

/// Render `docs/CAPABILITY-MATRIX.md`.
pub fn render(model: &Model, states: &BTreeMap<String, String>, links: &LinksFile) -> String {
    let reqs = tasks::req_ids(model);
    let mut out = String::from("# Capability matrix\n\n");
    out.push_str("Generated by `cargo xtask matrix generate` (T-0010) from the task blocks, the task table of `STATUS.md` and `docs/matrix-links.toml`. Do not edit by hand.\n");
    out.push_str("One row per task (R-07). A row advances past `green` only with a linked test, past `verified` only with hash-checked evidence, and to `accepted`/`done` only with a passing verify run record; `cargo xtask matrix check` enforces this.\n\n");
    out.push_str("| REQ | Task | Description | Tests | Evidence | Status |\n| --- | --- | --- | --- | --- | --- |\n");
    for t in &model.tasks {
        let l = links.task.iter().find(|l| l.id == t.id);
        let tests = match l {
            Some(l) if !l.tests.is_empty() => l
                .tests
                .iter()
                .map(|x| format!("`{x}`"))
                .collect::<Vec<_>>()
                .join("<br>"),
            Some(l) if !l.deferred.is_empty() => format!("deferred({})", l.deferred),
            _ => String::new(),
        };
        let evidence = l
            .map(|l| {
                l.evidence
                    .iter()
                    .map(|e| format!("`{e}`"))
                    .collect::<Vec<_>>()
                    .join("<br>")
            })
            .unwrap_or_default();
        let status = states.get(&t.id).map_or("todo", String::as_str);
        out.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} |\n",
            reqs.get(&t.id).map_or("REQ-UNK-00", String::as_str),
            t.id,
            md_cell(&t.title),
            tests,
            evidence,
            status
        ));
    }
    out
}

fn needs_test(state: &str) -> bool {
    matches!(state, "red" | "green" | "verified" | "accepted" | "done")
}

fn needs_evidence(state: &str) -> bool {
    matches!(state, "verified" | "accepted" | "done")
}

fn needs_run_record(state: &str) -> bool {
    matches!(state, "accepted" | "done")
}

/// True when a JSON verify summary has steps and none of them FAILED.
pub fn is_passing_run_record(json: &str) -> bool {
    let Ok(v) = serde_json::from_str::<serde_json::Value>(json) else {
        return false;
    };
    let Some(steps) = v.get("steps").and_then(|s| s.as_array()) else {
        return false;
    };
    !steps.is_empty()
        && steps
            .iter()
            .all(|s| s.get("status").and_then(|x| x.as_str()) != Some("FAIL"))
}

/// Check one test reference against the repository.
fn test_exists(root: &Path, r: &str) -> bool {
    let (path, name) = match r.split_once("::") {
        Some((p, n)) => (p, Some(n)),
        None => (r, None),
    };
    let Ok(text) = read_text(&root.join(path)) else {
        return false;
    };
    match name {
        None => true,
        Some(n) => text.contains(&format!("fn {n}(")),
    }
}

/// Core check, independent of the file system for the status table (used by unit tests).
pub fn check_rows(
    root: &Path,
    model: &Model,
    states: &BTreeMap<String, String>,
    links: &LinksFile,
) -> Vec<Finding> {
    let mut f = Vec::new();
    for t in &model.tasks {
        let state = states.get(&t.id).map_or("todo", String::as_str);
        let l = links.task.iter().find(|l| l.id == t.id);
        let loc = format!("docs/CAPABILITY-MATRIX.md:{}", t.id);
        let deferred = l.is_some_and(|l| !l.deferred.is_empty()) || state.starts_with("deferred(");
        if needs_test(state) && !deferred {
            match l {
                Some(l) if !l.tests.is_empty() => {
                    for r in &l.tests {
                        if !test_exists(root, r) {
                            f.push(Finding::new(
                                "matrix",
                                &loc,
                                format!("{state}: test reference `{r}` does not exist"),
                            ));
                        }
                    }
                }
                _ => f.push(Finding::new(
                    "matrix",
                    &loc,
                    format!("{state}: no linked test and no explicit deferral (R-07)"),
                )),
            }
        }
        if needs_evidence(state) {
            let ev: &[String] = l.map_or(&[], |l| l.evidence.as_slice());
            if ev.is_empty() {
                f.push(Finding::new(
                    "matrix",
                    &loc,
                    format!("{state}: no evidence linked"),
                ));
            }
            let mut passing = false;
            for e in ev {
                let Some((path, sha)) = e.rsplit_once('@') else {
                    f.push(Finding::new(
                        "matrix",
                        &loc,
                        format!("evidence `{e}` is not `path@sha256`"),
                    ));
                    continue;
                };
                match read_bytes(&root.join(path)) {
                    Ok(bytes) => {
                        if sha256_hex(&bytes) != sha {
                            f.push(Finding::new(
                                "matrix",
                                &loc,
                                format!("evidence `{path}` hash differs from the recorded sha256"),
                            ));
                        } else if path.ends_with(".json")
                            && is_passing_run_record(&String::from_utf8_lossy(&bytes))
                        {
                            passing = true;
                        }
                    }
                    Err(_) => f.push(Finding::new(
                        "matrix",
                        &loc,
                        format!("evidence `{path}` does not exist"),
                    )),
                }
            }
            if needs_run_record(state) && !passing {
                f.push(Finding::new("matrix", &loc, format!("{state}: no passing run record (a verify summary JSON without FAIL) among the evidence")));
            }
        }
    }
    f
}

/// `matrix generate`.
pub fn generate(root: &Path) -> Result<()> {
    let model = tasks::parse(&spec::load_master(root)?)?;
    let states = tasks::status_states(root, &model)?;
    let links = load_links(root)?;
    let p = root.join("docs").join("CAPABILITY-MATRIX.md");
    write_text(&p, &render(&model, &states, &links))?;
    println!(
        "matrix generate: wrote {} ({} rows)",
        rel(root, &p),
        model.tasks.len()
    );
    Ok(())
}

/// `matrix check`: the file is current and every row satisfies the link rules.
pub fn check(root: &Path) -> Vec<Finding> {
    let run = || -> Result<Vec<Finding>> {
        let model = tasks::parse(&spec::load_master(root)?)?;
        let states = tasks::status_states(root, &model)?;
        let links = load_links(root)?;
        let mut f = check_rows(root, &model, &states, &links);
        for l in &links.task {
            if model.task(&l.id).is_none() {
                f.push(Finding::new(
                    "matrix",
                    "docs/matrix-links.toml",
                    format!("unknown task {}", l.id),
                ));
            }
        }
        match read_text(&root.join("docs").join("CAPABILITY-MATRIX.md")) {
            Ok(cur) if cur == render(&model, &states, &links) => {}
            Ok(_) => f.push(Finding::new(
                "matrix",
                "docs/CAPABILITY-MATRIX.md",
                "is stale; run `cargo xtask matrix generate`",
            )),
            Err(e) => f.push(Finding::new("matrix", "docs/CAPABILITY-MATRIX.md", e.0)),
        }
        Ok(f)
    };
    run().unwrap_or_else(|e| vec![Finding::new("matrix", "docs/CAPABILITY-MATRIX.md", e.0)])
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tasks::{Phase, Task};

    fn model() -> Model {
        let t = |id: &str| Task {
            id: id.into(),
            title: "t".into(),
            phase: "P00".into(),
            tags: vec![],
            deps: vec![],
            size: "S".into(),
            owner: "x".into(),
            block: String::new(),
            spec_line: 1,
            seg: "P00".into(),
            seg_line: 1,
        };
        Model {
            tasks: vec![t("T-0001"), t("T-0002")],
            phases: vec![Phase {
                id: "P00".into(),
                name: "n".into(),
                first: "T-0001".into(),
                last: "T-0002".into(),
                milestone: "M0".into(),
                gate: "G00".into(),
                prefix: "GOV".into(),
            }],
            slices: vec![],
            e14: BTreeMap::new(),
        }
    }

    fn tmp(name: &str) -> std::path::PathBuf {
        let d = std::env::temp_dir().join(format!("hdd-matrix-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).expect("mkdir");
        d
    }

    #[test]
    fn generated_matrix_has_one_row_per_task_with_req_ids() {
        let states: BTreeMap<String, String> = [("T-0001".to_owned(), "done".to_owned())].into();
        let m = render(&model(), &states, &LinksFile::default());
        assert!(m.contains("| REQ-GOV-01 | T-0001 | t |  |  | done |"));
        assert!(m.contains("| REQ-GOV-02 | T-0002 | t |  |  | todo |"));
        assert_eq!(m.lines().filter(|l| l.starts_with("| REQ-")).count(), 2);
    }

    #[test]
    fn a_done_row_without_evidence_fails() {
        let root = tmp("noevidence");
        std::fs::write(root.join("t.rs"), "fn good_test() {}\n").expect("write");
        let states: BTreeMap<String, String> = [("T-0001".to_owned(), "done".to_owned())].into();
        let links = LinksFile {
            task: vec![Links {
                id: "T-0001".into(),
                tests: vec!["t.rs::good_test".into()],
                evidence: vec![],
                deferred: String::new(),
            }],
        };
        let f = check_rows(&root, &model(), &states, &links);
        assert!(
            f.iter().any(|x| x.message.contains("no evidence linked")),
            "{f:?}"
        );
        assert!(
            f.iter()
                .any(|x| x.message.contains("no passing run record")),
            "{f:?}"
        );
    }

    #[test]
    fn a_done_row_with_hash_checked_passing_evidence_passes_and_tampering_fails() {
        let root = tmp("good");
        std::fs::write(root.join("t.rs"), "fn good_test() {}\n").expect("write");
        let run = r#"{"steps":[{"status":"PASS"},{"status":"UNVERIFIED(tool_unavailable)"}]}"#;
        std::fs::write(root.join("run.json"), run).expect("write");
        let sha = sha256_hex(run.as_bytes());
        let states: BTreeMap<String, String> = [("T-0001".to_owned(), "done".to_owned())].into();
        let links = LinksFile {
            task: vec![Links {
                id: "T-0001".into(),
                tests: vec!["t.rs::good_test".into()],
                evidence: vec![format!("run.json@{sha}")],
                deferred: String::new(),
            }],
        };
        assert!(check_rows(&root, &model(), &states, &links).is_empty());
        std::fs::write(root.join("run.json"), format!("{run} ")).expect("tamper");
        let f = check_rows(&root, &model(), &states, &links);
        assert!(
            f.iter().any(|x| x.message.contains("hash differs")),
            "{f:?}"
        );
    }

    #[test]
    fn failing_run_record_and_missing_test_are_rejected() {
        let root = tmp("bad");
        let run = r#"{"steps":[{"status":"FAIL"}]}"#;
        std::fs::write(root.join("run.json"), run).expect("write");
        let sha = sha256_hex(run.as_bytes());
        let states: BTreeMap<String, String> =
            [("T-0001".to_owned(), "accepted".to_owned())].into();
        let links = LinksFile {
            task: vec![Links {
                id: "T-0001".into(),
                tests: vec!["nope.rs::x".into()],
                evidence: vec![format!("run.json@{sha}")],
                deferred: String::new(),
            }],
        };
        let f = check_rows(&root, &model(), &states, &links);
        assert!(f.iter().any(|x| x.message.contains("does not exist")));
        assert!(
            f.iter()
                .any(|x| x.message.contains("no passing run record"))
        );
    }

    #[test]
    fn todo_rows_and_explicit_deferrals_need_nothing() {
        let root = tmp("todo");
        let states: BTreeMap<String, String> = [("T-0002".to_owned(), "green".to_owned())].into();
        let links = LinksFile {
            task: vec![Links {
                id: "T-0002".into(),
                tests: vec![],
                evidence: vec![],
                deferred: "needs operator".into(),
            }],
        };
        assert!(check_rows(&root, &model(), &states, &links).is_empty());
        let no_link = check_rows(&root, &model(), &states, &LinksFile::default());
        assert_eq!(no_link.len(), 1, "green without test or deferral must fail");
    }

    #[test]
    fn run_record_detection() {
        assert!(is_passing_run_record(r#"{"steps":[{"status":"PASS"}]}"#));
        assert!(!is_passing_run_record(r#"{"steps":[]}"#));
        assert!(!is_passing_run_record("garbage"));
    }
}
