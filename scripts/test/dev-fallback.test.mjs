// Tests for the per-run port fallback in the dev launcher.
//
// The committed demo/hdd-dev.yaml keeps its documented endpoints (proxy 8080,
// admin 9090) even when another process on the machine holds one of those ports.
// `npm run dev` probes them and, only for that run, writes a generated profile under
// the git-ignored hdd-data/ directory. These tests inject the port probe so the
// fallback logic is deterministic and nothing binds a socket.

import assert from 'node:assert/strict';
import test from 'node:test';

import { generateProfileText, planEndpoints } from '../dev.mjs';
import { sameUrl } from '../lib/util.mjs';

function baseConfig() {
  return {
    text: [
      '# committed rehearsal profile',
      'listen: "127.0.0.1:8080"',
      'admin_listen: "127.0.0.1:9090"',
      'data_dir: "hdd-data"',
      'log_path: "hdd-data/events.jsonl"',
      'admin_token_env: HDD_ADMIN_TOKEN',
      'trusted_proxies: []',
      '',
      'sites:',
      '  - host: "127.0.0.1"',
      '    origin: "http://127.0.0.1:8082"',
      '    stack: node',
      '    mode: block',
      '    strictness: balanced',
      '    public_url: "http://127.0.0.1:8080"',
      '    preserve_host: true',
      '    ban:',
      '      enabled: true',
      '      ttl_ladder_seconds: [60, 600, 3600]',
      '',
    ].join('\n'),
    listen: { host: '127.0.0.1', port: 8080 },
    admin: { host: '127.0.0.1', port: 9090 },
    origin: { host: '127.0.0.1', port: 8082, url: 'http://127.0.0.1:8082' },
    stack: 'node',
    loginPath: '/admin/login',
    siteHost: '127.0.0.1',
    mode: 'block',
    configPath: 'demo/hdd-dev.yaml',
  };
}

const probeBusy = (busyPorts) => async (port) => busyPorts.includes(port);

test('the configured endpoints are used when they are free', async () => {
  const plan = await planEndpoints(baseConfig(), { isPortOpen: probeBusy([]), configLabel: 'demo/hdd-dev.yaml' });
  assert.equal(plan.ok, true);
  assert.equal(plan.proxy.port, 8080);
  assert.equal(plan.admin.port, 9090);
  assert.equal(plan.origin.port, 8082);
  assert.equal(plan.needsGeneratedProfile, false);
  assert.deepEqual(plan.fallbackLines, []);
});

test('a busy configured proxy port falls back to the first free pair and says so', async () => {
  const plan = await planEndpoints(baseConfig(), {
    isPortOpen: probeBusy([8080]),
    configLabel: 'demo/hdd-dev.yaml',
  });
  assert.equal(plan.ok, true);
  assert.equal(plan.proxy.port, 18080);
  assert.equal(plan.admin.port, 19090);
  assert.equal(plan.needsGeneratedProfile, true);
  assert.equal(plan.fallbackLines.length, 1, 'one clear fallback line');
  const line = plan.fallbackLines[0];
  assert.match(line, /port 8080/);
  assert.match(line, /unavailable/);
  assert.match(line, /proxy http:\/\/127\.0\.0\.1:18080/);
  assert.match(line, /admin http:\/\/127\.0\.0\.1:19090/);
  assert.match(line, /keeps 8080\/9090/);

  const generated = generateProfileText(baseConfig(), plan, 'demo/hdd-dev.yaml');
  assert.match(generated, /GENERATED by `npm run dev`/);
  assert.match(generated, /listen: "127\.0\.0\.1:18080"/);
  assert.match(generated, /admin_listen: "127\.0\.0\.1:19090"/);
  assert.match(generated, /public_url: "http:\/\/127\.0\.0\.1:18080"/);
  assert.match(generated, /origin: "http:\/\/127\.0\.0\.1:8082"/);
  assert.match(generated, /mode: block/);
  assert.match(generated, /field_hints|ban:/, 'the rest of the committed profile is kept');
});

test('the fallback pair is skipped while it is busy too', async () => {
  const plan = await planEndpoints(baseConfig(), {
    isPortOpen: probeBusy([8080, 18080]),
    configLabel: 'demo/hdd-dev.yaml',
  });
  assert.equal(plan.ok, true);
  assert.equal(plan.proxy.port, 18081);
  assert.equal(plan.admin.port, 19091);
});

test('a busy admin port also triggers a fallback pair', async () => {
  const plan = await planEndpoints(baseConfig(), {
    isPortOpen: probeBusy([9090]),
    configLabel: 'demo/hdd-dev.yaml',
  });
  assert.equal(plan.ok, true);
  assert.equal(plan.proxy.port, 18080);
  assert.equal(plan.admin.port, 19090);
  assert.match(plan.fallbackLines[0], /port 9090/);
  assert.match(plan.fallbackLines[0], /keeps 8080\/9090/);
});

test('a busy lab origin falls back to a free origin port with its own line', async () => {
  const plan = await planEndpoints(baseConfig(), {
    isPortOpen: probeBusy([8082]),
    configLabel: 'demo/hdd-dev.yaml',
  });
  assert.equal(plan.ok, true);
  assert.equal(plan.origin.port, 18082);
  assert.equal(plan.changed.origin, true);
  assert.match(plan.fallbackLines[0], /configured lab origin/);
  assert.match(plan.fallbackLines[0], /18082/);
  const generated = generateProfileText(baseConfig(), plan, 'demo/hdd-dev.yaml');
  assert.match(generated, /origin: "http:\/\/127\.0\.0\.1:18082"/);
});

test('when every candidate port is busy the launcher fails clearly instead of guessing', async () => {
  const busy = [
    8080, 9090, 8082,
    18080, 18081, 18082, 18083, 18084,
    19090, 19091, 19092, 19093, 19094,
  ];
  const plan = await planEndpoints(baseConfig(), { isPortOpen: probeBusy(busy), configLabel: 'demo/hdd-dev.yaml' });
  assert.equal(plan.ok, false);
  assert.match(plan.error, /no free fallback/);
  assert.match(plan.error, /Nothing was started/);
});

test('attack.mjs compares URLs to derive the direct/proxy kind', () => {
  assert.equal(sameUrl('http://127.0.0.1:18080/', 'http://127.0.0.1:18080'), true);
  assert.equal(sameUrl('http://127.0.0.1:18080/login', 'http://127.0.0.1:18080/'), false);
  assert.equal(sameUrl('http://127.0.0.1:8081', 'http://127.0.0.1:8080'), false);
  assert.equal(sameUrl('not a url', 'http://127.0.0.1:8080'), false);
});
